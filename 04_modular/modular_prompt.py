# 04 단계: 랭체인의 프롬프트 템플릿 컴포넌트를 독립 모듈로 분리 선언합니다.
#
# 프롬프트 문구만 이 파일에서 관리하면, 모델(modular_llm.py)이나 실행 코드(modular_main.py)를
# 건드리지 않고도 AI의 역할과 답변 방식을 바꿀 수 있습니다.
#
# 이 모듈이 외부에 제공하는 것
#   - simple_prompt : {concept} 변수를 받는 프롬프트 템플릿 (modular_main.py가 import 해서 사용)
#
# 체인에서의 위치: [프롬프트] -> 모델 -> 파서   (이 파일은 맨 앞 단계)

from langchain_core.prompts import ChatPromptTemplate    # 변수가 들어간 문자열을 모델 입력(메시지)으로 만들어 주는 템플릿 클래스

# - simple_prompt: 다른 파이썬 파일에서 import하여 재사용할 수 있도록 정의된 전역 프롬프트 템플릿
# - {concept} 변수를 대입받아 작동하도록 구성되었습니다.
#
# from_template(): 문자열 하나를 사용자(user) 메시지 한 개짜리 채팅 프롬프트로 만듭니다.
#   - 문자열 안의 {concept}는 변수 자리표시자이며, invoke({"concept": "..."}) 또는
#     format(concept="...") 호출 시 실제 값으로 치환됩니다.
#   - 아래처럼 문자열 두 개를 나란히 쓰면 파이썬이 하나로 이어 붙입니다. (줄이 길어지는 것을 방지)
#   - 앞부분은 AI의 역할(페르소나)과 설명 방식을, 뒷부분은 입력받을 개념을 지정합니다.
#   - "\n\n"은 빈 줄을 넣어 지시문과 입력값을 구분하는 줄바꿈입니다.
#   - 문구 안에 중괄호({ })를 그대로 쓰려면 {{ }} 처럼 두 번 써야 합니다. (변수로 해석되기 때문)
simple_prompt = ChatPromptTemplate.from_template(
    "당신은 초등학생도 쉽게 이해하도록 돕는 유능한 교육용 튜터입니다. "
    "다음 개념에 대해 비유를 섞어 설명해 주세요.\n\n개념: {concept}"
)
